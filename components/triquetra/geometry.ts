/**
 * Геометрия Триквестра — единственный источник координат для всей визуализации.
 *
 * Построение: три окружности радиуса R с центрами на радиусе D под углами 30°, 150°, 270°.
 * Условие R > D обязательно: именно оно даёт область тройного перекрытия — ЯДРО.
 * При R = D три лепестка сходятся в одну точку и ядра не существует.
 *
 * Все координаты выдаются в системе SVG (ось Y вниз).
 */

/** Радиус образующих окружностей. */
export const R = 1;

/** Радиус, на котором стоят центры образующих окружностей. Должен быть < R. */
export const D = 0.86;

/** Половина хорды пересечения двух соседних окружностей. */
export const H = Math.sqrt(R * R - (3 * D * D) / 4);

/** Радиус вершины лепестка (внешний конец). */
export const TIP = D / 2 + H;

/**
 * Радиус внутреннего конца лепестка. Отрицателен — конец уходит ЗА центр,
 * на противоположную сторону. Это и создаёт ядро.
 */
export const INNER = D / 2 - H;

/** Y-координата вершины лепестка в локальной системе лепестка (смотрит вверх). */
export const Y_TIP = -TIP;

/** Y-координата внутреннего конца лепестка в его локальной системе. */
export const Y_INNER = -INNER;

/** Длина оси лепестка — путь, который проходит заполнение от вершины к центру. */
export const AXIS_LENGTH = Y_INNER - Y_TIP;

/** Радиусы обрамляющих колец. */
export const RING_INNER = 1.24;
export const RING_OUTER = 1.34;

/** Половина стороны viewBox. */
export const VIEW = 1.45;

/** Расстояние от оси лепестка до центра образующей окружности. */
export const PETAL_CENTER_OFFSET = Math.sqrt(R * R - H * H);

/** Половина ширины лепестка в самом широком месте. */
export const PETAL_HALF_WIDTH = R - PETAL_CENTER_OFFSET;

export const VIEW_BOX = `${-VIEW} ${-VIEW} ${VIEW * 2} ${VIEW * 2}`;

/** Три оболочки в порядке лепестков: Дух наверху — «дух ведёт». */
export const SHELLS = ['SPIRIT', 'MIND', 'BODY'] as const;
export type Shell = (typeof SHELLS)[number];

/** Угол поворота лепестка каждой оболочки. Дух — 0° (вверх). */
export const SHELL_ROTATION: Record<Shell, number> = {
  SPIRIT: 0,
  MIND: 120,
  BODY: 240,
};

export const SHELL_LABEL: Record<Shell, string> = {
  SPIRIT: 'Дух',
  MIND: 'Разум',
  BODY: 'Тело',
};

/**
 * Путь одного лепестка (vesica piscis) в локальной системе: вершина вверху,
 * внутренний конец ниже центра.
 *
 * Оба флага sweep = 0: выведено в системе SVG, где угол растёт по часовой
 * стрелке, а обе дуги проходятся в сторону убывания угла. Дуги по 83.7°,
 * поэтому large-arc = 0.
 */
export function petalPath(): string {
  const inner = `0 ${Y_INNER.toFixed(6)}`;
  const tip = `0 ${Y_TIP.toFixed(6)}`;
  const r = `${R} ${R}`;
  return `M ${inner} A ${r} 0 0 0 ${tip} A ${r} 0 0 0 ${inner} Z`;
}

/**
 * Прямоугольник-маска для заполнения лепестка от вершины внутрь.
 * Сдвигается по Y на `fill * AXIS_LENGTH` — так открывается ровно верхняя
 * доля лепестка. Высота с большим запасом, чтобы верхний край маски
 * оставался выше вершины при любом уровне заполнения.
 */
export const MASK_RECT = {
  x: -0.7,
  y: -3,
  width: 1.4,
  height: 3 + Y_TIP,
} as const;

/**
 * Область действия маски. Задавать ОБЯЗАТЕЛЬНО.
 *
 * У элемента <mask> собственные x/y/width/height по умолчанию равны
 * -10% / -10% / 120% / 120%, и при maskUnits="userSpaceOnUse" эти проценты
 * считаются от вьюпорта, а не от лепестка. Область получается
 * y ∈ [-0.29, 3.19]: всё выше обрезается, вершины лепестков исчезают, и
 * заполнение выглядит полосой у центра вместо роста от вершины.
 */
export const MASK_REGION = {
  x: -VIEW,
  y: -VIEW,
  width: VIEW * 2,
  height: VIEW * 2,
} as const;

/** Смещение маски для заданной доли заполнения (0..1), в единицах viewBox. */
export function maskOffset(fill: number): number {
  return clamp01(fill) * AXIS_LENGTH;
}

export function clamp01(v: number): number {
  return v < 0 ? 0 : v > 1 ? 1 : v;
}
